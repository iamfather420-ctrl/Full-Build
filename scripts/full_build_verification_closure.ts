import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';

const artifactNames = [
  'formal-aggregation.json',
  'z3-120-formal-verification-summary.json',
  'daisy-brain-activation-gate.json',
  'system-46-gates.json',
  'execution-gates.json'
];
const before = new Map<string, number>();
for (const name of artifactNames) {
  const file = path.resolve('artifacts', name);
  before.set(name, fs.existsSync(file) ? fs.statSync(file).mtimeMs : -1);
}

const npm = process.platform === 'win32' ? 'npm.cmd' : 'npm';
const closureRunId = `closure_${Date.now()}_${process.pid}`;
const env = {
  ...process.env,
  SOLVEX_ENV: 'ci',
  PAYMENTS_ENABLED: 'false',
  SOLVEX_CLOSURE_RUN_ID: closureRunId
};
// Keep one authoritative execution path. The 15-gate pipeline already
// exercises enterprise invariants and 54-node coverage; the 120-case
// aggregation owns the DFRL+DH corpus and 46-gate run. Avoid invoking those
// same suites again through their standalone aliases.
const commands = [
  'verify:release-safety',
  'verify:payments-disabled',
  // verify:120 creates the commit-bound DFRL report and the isolated 46-gate
  // pipeline, which also emits execution-gates.json. Do not rerun the
  // authoritative pipeline as a separate duplicate step.
  'verify:120',
  'verify:ci'
];
const failures: string[] = [];

for (const script of commands) {
  console.log('\n[LOCAL VERIFICATION] npm run ' + script);
  const result = spawnSync(npm, ['run', script], { stdio: 'inherit', env, shell: process.platform === 'win32' });
  if (result.error) {
    failures.push(script + ': ' + result.error.message);
  } else if (result.status !== 0) {
    failures.push(script + ': exit status ' + String(result.status));
  }
}

for (const name of artifactNames) {
  const file = path.resolve('artifacts', name);
  const previous = before.get(name) ?? -1;
  if (!fs.existsSync(file)) {
    failures.push('fresh formal artifact missing: ' + name);
  } else if (fs.statSync(file).mtimeMs <= previous) {
    failures.push('formal artifact was not regenerated by this closure run: ' + name);
  }
}

// The former sandboxVerificationPipeline.ts module is absent from the checked-in
// source tree. The current dependency-free release contract is verify_payments_disabled.mjs,
// which is executed above and asserts no provider network calls and a permanent disabled
// adapter boundary. Do not fabricate the missing legacy module or report provider tests as run.
const paymentBoundarySource = path.resolve('scripts/verify_payments_disabled.mjs');
if (!fs.existsSync(paymentBoundarySource)) {
  failures.push('payment safety verification BLOCKED: scripts/verify_payments_disabled.mjs is absent.');
}

console.log('\n============================================================');
console.log('SOLVEX + DAISY HAMINJA — LOCAL VERIFICATION CLOSURE');
console.log('Production readiness is evaluated separately and is not promoted by local tests.');
console.log('Authentication remains fail-closed; payments remain disabled.');
if (failures.length) {
  console.error('\nBLOCKED / FAILED ITEMS (' + failures.length + '):');
  for (const failure of failures) console.error(' - ' + failure);
  console.error('\nLOCAL VERIFICATION CLOSURE: NOT COMPLETE');
  process.exitCode = 1;
} else {
  console.log('\nAll selected local verification suites passed and formal artifacts were freshly generated.');
  console.log('This does not certify production OIDC, tenant isolation, Neon RLS, backup/restore, or deployment readiness.');
  console.log('LOCAL VERIFICATION CLOSURE: VERIFIED (LOCAL SCOPE ONLY)');
}
